export const PARTNER_TAG = 'stylematch-21';

export const buildAmazonSearchUrl = (query, tag = PARTNER_TAG) => {
  const clean = String(query || '').trim();
  return `https://www.amazon.in/s?k=${encodeURIComponent(clean)}&tag=${tag}`;
};

export const buildAmazonProductUrl = (asin, query, tag = PARTNER_TAG) => {
  if (asin && /^[A-Z0-9]{10}$/i.test(asin)) {
    return `https://www.amazon.in/dp/${asin}?tag=${tag}`;
  }
  return buildAmazonSearchUrl(query || asin, tag);
};

