// Helper to find the best-matched looks for a user's selection and active style filter
export const getShopTheLookRecommendations = (selection = {}, activeStyle = '') => {
  const gender = (selection.category || 'Women').trim();

  // Match by gender
  let matches = shopTheLookData.filter((look) => {
    return look.gender.toLowerCase() === gender.toLowerCase();
  });

  // If no gender matches, fallback to Women
  if (!matches.length) {
    matches = shopTheLookData.filter((look) => look.gender === 'Women');
  }

  // Filter or prioritize by style if activeStyle is chosen
  if (activeStyle) {
    const exactMatches = matches.filter((look) => look.style === activeStyle);
    if (exactMatches.length > 0) {
      return exactMatches;
    }
    const aliasMatches = matches.filter((look) => {
      return Array.isArray(look.styleAliases) && look.styleAliases.includes(activeStyle);
    });
    if (aliasMatches.length > 0) {
      return aliasMatches;
    }
  }

  return matches;
};
